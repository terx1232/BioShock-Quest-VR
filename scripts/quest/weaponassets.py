"""Build named weapon/upgrade draw signatures from the installed game's assets."""
from pathlib import Path
import hashlib
import json
import re
import subprocess

ROOT=Path(__file__).resolve().parents[2]
MODELS={
    'Wrench':['WP_WrenchMesh'],
    'Pistol':['WP_PistolMesh','PI_UpgradeBalt','PI_UpgradeA','PI_UpgradeB'],
    'TommyGun':['TommyGunMESH','TG_upgradeA','TG_upgradeB'],
    'Shotgun':['WP_ShotgunMesh','SG_UpgradeA','SG_UpgradeB'],
    'ChemicalThrower':['WP_ChemicalThrowerMesh','CT_UpgradeA','CT_UpgradeB'],
    'Crossbow':['WP_CrossbowMesh','XB_UpgradeA','XB_UpgradeB_Mesh'],
    'GrenadeLauncher':['WP_GrenadeLauncherMesh','GL_UpgradeA','GL_UpgradeB'],
    'PlasmidEquip':['PlasmidEquipMESH'],
}

def signatures(text):
    result=[]
    # One section is one draw; transparent and opaque sections stay distinct.
    lods=list(re.finditer(r'Lods\[\d+\]\s*=\s*\{(.*?)NumVerts\s*=\s*(\d+)',text,re.S))
    if lods:
        for lod in lods:
            result.extend((int(lod[2]),int(f)) for f in re.findall(r'NumFaces\s*=\s*(\d+)',lod[1]))
    else:
        verts=re.findall(r'NumVerts\s*=\s*(\d+)',text)
        faces=re.findall(r'NumFaces\s*=\s*(\d+)',text)
        if len(verts)==1:result.extend((int(verts[0]),int(f)) for f in faces)
    return sorted(set(result))

def main():
    import importlib.util
    spec=importlib.util.spec_from_file_location('quest_asset_builder',ROOT/'scripts/quest/builder.py')
    builder=importlib.util.module_from_spec(spec);spec.loader.exec_module(builder)
    game=builder.find_game('auto');package=game/'Builds/Release/ShockGame.U'
    folder=ROOT/'build/work/weapons77';folder.mkdir(parents=True,exist_ok=True)
    records=[];ranges=[(0,0)];roots=[]
    for family,models in MODELS.items():
        first=len(records);roots.append((family,models[0]))
        for mesh in models:
            result=subprocess.run([str(ROOT/'dependencies/build/umodel/umodel.exe'),'-dump',
                '-path='+str(package.parent),'ShockGame.U',mesh],capture_output=True,text=True,check=True)
            text=result.stdout+result.stderr;(folder/(mesh+'.txt')).write_text(text)
            pairs=signatures(text)
            if not pairs:raise ValueError('No verified geometry for '+mesh)
            records.extend({'family':family,'mesh':mesh,'vertices':v,'primitives':p} for v,p in pairs)
        ranges.append((first,len(records)-first))
    assert any(x['mesh']=='WP_WrenchMesh' and (x['vertices'],x['primitives'])==(1953,1686) for x in records)
    assert any(x['mesh']=='WP_PistolMesh' and (x['vertices'],x['primitives'])==(2361,2824) for x in records)
    data={'packageSha256':hashlib.sha256(package.read_bytes()).hexdigest(),'records':records}
    out=ROOT/'source/native/data';out.mkdir(exist_ok=True)
    (out/'weaponassets.json').write_text(json.dumps(data,indent=2)+'\n')
    lines=['// Generated by scripts/quest/weaponassets.py from the installed ShockGame.U.',
        '// Package SHA256: '+data['packageSha256'],'namespace weaponassets {',
        'enum class Model : unsigned { None, '+', '.join(MODELS)+', Count };',
        'struct Pair { unsigned vertices,primitives; };','inline constexpr Pair pairs[]={']
    for x in records:lines.append('    {%d,%d}, // %s %s'%(x['vertices'],x['primitives'],x['family'],x['mesh']))
    lines+=['};','struct Range { unsigned first,count; };','inline constexpr Range ranges[]={'+','.join('{%d,%d}'%x for x in ranges)+'};',
        'inline Model Find(const wchar_t* name){','    if(!name)return Model::None;']
    lines+=['    if(!_wcsicmp(name,L"'+mesh+'"))return Model::'+family+';' for family,mesh in roots]
    lines+=['    return Model::None;','}',
        'inline bool Matches(Model model,unsigned vertices,unsigned primitives){',
        '    unsigned id=unsigned(model);if(!id||id>=unsigned(Model::Count))return false;',
        '    const auto range=ranges[id];for(unsigned i=range.first;i<range.first+range.count;i++)',
        '        if(pairs[i].vertices==vertices&&pairs[i].primitives==primitives)return true;',
        '    return false;','}','}']
    (ROOT/'source/native/src/weaponassets.inc').write_text('\n'.join(lines)+'\n')
    print('Verified %d geometry signatures across %d weapon/tool families and their upgrades'%(len(records),len(MODELS)))

if __name__=='__main__':main()
